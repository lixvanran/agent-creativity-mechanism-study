def apply(path):
    s = io.open(path, encoding="utf-8").read()
    orig = s
    name = os.path.basename(path)
    print("patch_docs_mine: %s" % path)
    for f, mode, mark, old, new, tag in RULES:
        if f not in name:
            continue
        # ★ 幂等判定必须用"新文本里独有的串"（坑 26）。
        #   坑 12/26 的教训：marker 太泛 ⇒ 脚本误判"已打过" ⇒ 静默漏改。
        #   ��� mode=delete ⇒ 判据是"old 已不在"；mode=replace ⇒ 判据是"mark 在"。
        if mode == "delete":
            if old not in s:
                print("  · 已在（目标已不存在），跳过：%s" % tag)
                continue
        else:
            # ★ 自检：marker 必须是 new 文本里**真的存在**的串
            #   （踩坑实录：marker 写成 "### 4.3" 而实际标题是 "### 4.2"
            #     ⇒ marker 永远匹配不上 ⇒ 旧文本又已被别人改掉 ⇒ 报"锚点未命中"
            #     ⇒ 而如果 old 恰好也不在，就会被当成"已应用"而**静默漏改**）
            if mark and mark not in new:
                raise SystemExit("✗ 规则 %s 的 marker 不在 new 文本里 ⇒ 永远匹配不上：%r" % (tag, mark))
            if mark and mark in s:
                print("  · 已在，跳过：%s" % tag)
                continue
            if not old:
                raise SystemExit("✗ 规则缺少 old：%s" % tag)
        if old not in s:
            print("  ✗ 锚点未命中：%s" % tag)
            print("    期望片段：%r" % (old[:90],))
            raise SystemExit("✗ patch_docs_mine 锚点未命中：%s（%s）" % (tag, path))
        s = s.replace(old, new, 1)
        print("  ✓ 应用：%s" % tag)
    if s != orig:
        io.open(path, "w", encoding="utf-8").write(s)
        print("  → 已写盘")
    else:
        print("  （无变化）")
    return s != orig


