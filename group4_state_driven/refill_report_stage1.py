def main() -> int:
    if not os.path.exists(REPORT):
        print("✘ 找不到报告：%s" % REPORT)
        return 2
    if not os.path.exists(ANALYSIS):
        print("✘ 找不到 analysis：%s" % ANALYSIS)
        return 2

    # ── 先核 analysis 里的数与我们要写进报告的一致（★ 防止手抄错）──
    d = json.load(open(ANALYSIS, encoding="utf-8"))
    expect = {
        "rank_change_n": 8, "rank_change_count": 3, "rank_change_rate": 0.375,
        "n_scorable": 8, "n_unscoreable": 1,
        "candidate_homogeneity_rate": 0.875, "target_change_rate": 1.0,
    }
    for k, v in expect.items():
        got = d.get(k)
        if got != v:
            print("✘ analysis 的 %s = %r ≠ 预期 %r ⇒ ⇒ ★ 报告不该按这个数重填" % (k, got, v))
            return 2
    zc = d.get("zero_classification") or {}
    if zc.get("unscoreable_none") != ["T07-3"] or zc.get("content_zero"):
        print("✘ zero_classification 不符预期：%r" % (zc,))
        return 2

    s = open(REPORT, encoding="utf-8").read()
    n_done, n_skip, n_miss = 0, 0, []
    for old, new in REPLACEMENTS:
        c = s.count(old)
        if c == 0:
            n_skip += 1
            continue
        if c > 1:
            n_miss.append((old[:70], "命中 %d 次（★ 不唯一）" % c))
            continue
        s = s.replace(old, new, 1)
        n_done += 1

    if n_miss:
        print("✘ 有 %d 处替换【不唯一命中】⇒ ⇒ 未写入（★ 报告可能被改成半新半旧）" % len(n_miss))
        for o, w in n_miss:
            print("   · %s ⇒ %s" % (o, w))
        return 2

    # ── 写盘（★ 原子写）──
    tmp = REPORT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(s)
    os.replace(tmp, REPORT)
    print("✔ 已重填 %d 处（★ 已是新值而跳过 %d 处 ⇒ 幂等）" % (n_done, n_skip))
    return 0


if __name__ == "__main__":
    sys.exit(main())
