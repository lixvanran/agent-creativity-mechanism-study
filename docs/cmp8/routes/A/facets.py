# 断言抽取：在既有 ASSERT_MAIN 基础上加一条**自足性**要求（减少 F5 风险：
# 关键结论常常靠「多血质」这类专名被命中，代词会让命中失败）。
EXTRACT_Q = """从下面这段回答里，逐条列出其中**可判真假的陈述**。
一行一条，最多 12 条。

要求：
- 一条一个可独立核验的事实性陈述。
- **每条必须自足**：写出主体名称与具体数值/条件/规则，
  不要用「它」「该」「此项」「上述」代替主语。
- 不要观点、不要建议、不要寒暄。

文本：
{t}"""

# 拆分复合断言：一条断言内部含两个互不依赖的承重项时，拆成 2 张（协议 §1.2 允许拆细）。
SPLIT_Q = """把下面这些陈述各自拆成可以分别核验的独立陈述。
如果某一条其实只包含一个陈述，就原样保留它。
一行一条，只输出拆分结果，不要编号，不要解释。

文本：
{t}"""

# 内部核验：协议 §4.6 的四分类 + 例外条款 + 依据编号。
# ⚠️ 这里的示例必须是**任务无关的合成示例**，禁止写入 U1–U4 的任何内容。
CHECK_Q = """下面是一份「依据条目列表」、一个问题，以及若干条待核验的陈述。

第一步：这条陈述是**只复述了问题里已经给出的情形**，还是**断言**？
判据：只要陈述里含有**超出问题本身**的信息（数字/阈值/名称/规则/主体关系/比较/归类），
就当它是断言；**由问题里的数值加上依据规则推导出的结论，是断言，不是复述**。
只复述情形的，答「非主张」。

第二步：对断言，判断它与依据条目的关系，只回答一个词：
- 「支持」：依据条目明确认可或蕴含该条。改写、简称、换词但含义相同，也算支持。
- 「矛盾」：依据条目明确讲了与之相反的内容（含数字对不上、阈值不同、方向相反）。
- 「未提及」：依据条目没有讲到，或讲的是别的事。**不确定时一律答「未提及」。**

第三步：若第二步判为「支持」或「矛盾」，在同一个词后面用一个空格写出
支持它的那一条依据的**编号**（如：支持 3）。若有多条支持，写第一个即可。

一行一条，顺序对应，不要解释，不要补充。

问题：
{ask}

依据条目：
{ev}

待核验的陈述：
{claims}"""


def facet_line(fid: str) -> str:
    """把一条承载面写成提示词里的一段程序说明。"""
    return FACETS[fid][1]


def facet_text(fid: str) -> str:
    """同 facet_line（别名，语义更准：它是「注入文本」而不是「行」）。"""
    return FACETS[fid][1]


def facet_name(fid: str) -> str:
    return FACETS[fid][0]


def all_prompt_strings() -> list[tuple[str, str]]:
    """返回 (来源, 字符串) 列表，供 leakage / 黑名单扫描用。"""
    out = [
        ("OUT_SPEC", OUT_SPEC),
        ("SLOT_Q", SLOT_Q),
        ("RESAMPLE_Q", RESAMPLE_Q),
        ("EXTRACT_Q", EXTRACT_Q),
        ("SPLIT_Q", SPLIT_Q),
        ("CHECK_Q", CHECK_Q),
    ]
    for fid, (name, text, _why) in FACETS.items():
        out.append(("FACET:%s:name" % fid, name))
        out.append(("FACET:%s:text" % fid, text))
        out.append(("FACET:%s:why" % fid, _why))
    return out
