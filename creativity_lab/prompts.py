# ---------------- 评估器强度实验用（ToT 式 value / vote） ----------------
# ★ 放这里而不是实验脚本里：leakage.py 只扫 prompts.py ⇒ 新提示词必须过同一道扫描。
# ★ VALUE_Q：ToT 的 "value" 组件（对每个候选**独立**打分）
# ★ VOTE_Q：ToT 的 "vote" 组件（一次比较多个候选，选一个）
# ★ 两者都是**中性**问法：不提示答案类别、不暗示"要选不寻常的"。

VALUE_Q = """下面是一份独立写成的答复。

{cand}

请评价这份答复的质量：观点是否明确、依据是否具体、是否真的回答了问题。
只按上面三条判断，不要考虑它与其他答案的关系，也不要追求标新立异。
先给 1-10 分（10 = 三条都满足），再写不超过 40 字的理由。
用 JSON 格式输出：{{"score": <整数>, "why": "<不超过40字>"}}"""

VOTE_Q = """同一个问题下有若干份**各自独立**写成的答复：

{arts}

请选出其中**最好的一份**（观点明确、依据具体、真的回答了问题），
先写 60-120 字说明为什么选它，然后输出它的编号（1 到 {n}）。
不要重写、不要融合、不要拼接。用 JSON 格式输出：{{"pick": <编号>, "why": "<不超过120字>"}}"""
